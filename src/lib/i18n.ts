const dictionaries: Record<Lang, Record<MessageKey, string>> = { en, no };

export function detectLang(): Lang {
  const code = navigator.language.toLowerCase();
  return code.startsWith("nb") || code.startsWith("nn") || code.startsWith("no") ? "no" : "en";
}

export function localeTag(lang: Lang): string {
  return lang === "no" ? "nb-NO" : "en-GB";
}

export function t(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  let text = dictionaries[lang][key] || en[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function mapKnownError(lang: Lang, message: string): string {
  const table: Record<string, MessageKey> = {
    "That group code was not found": "groupNotFound",
    "Could not create a group": "couldNotCreateGroup",
    "Wrong email or password.": "wrongEmailOrPassword",
    "Spond is not connected on this computer. Sign in again.": "spondNotConnected",
    "That Google link is not a live calendar feed. In Google Calendar: Settings → the calendar → Integrate calendar → copy the secret address in iCal format (it ends with basic.ics).":
      "googleIcalHelp",
    "That link did not return a calendar file.": "notACalendarFile",
    "The calendar file had no events in it.": "calendarFileEmpty",
    "Could not fetch that calendar URL": "couldNotFetchCalendar",
    "Could not import that calendar URL": "couldNotImportCalendar",
  };
  const key = table[message];
  return key ? t(lang, key) : message;
}
